export async function regenerateNotes(
  orgId: string,
  reportDate: Date,
  userId: string
): Promise<FinancialNote[]> {
  // Delete existing auto-generated notes
  await db
    .delete(financialNotes)
    .where(
      and(
        eq(financialNotes.orgId, orgId),
        eq(financialNotes.autoGenerated, true)
      )
    );

  return generateDefaultNotes(orgId, reportDate, userId);
}
