import { z } from 'zod';
import { eq, and, desc } from 'drizzle-orm';
import { db, financialNotes, accounts, organisations } from '../db/schema';
import { AppError } from '../lib/errors';
import { getBalanceSheet, getProfitAndLoss, getCashFlowStatement, getStatementOfChangesInEquity, getTrialBalance } from './ledger.service';

export const noteSchema = z.object({
  noteNumber: z.string(),
  title: z.string(),
  content: z.string().optional(),
  autoGenerated: z.boolean().default(true),
  sourceReport: z.string().optional(),
  noteData: z.any().optional(),
  sortOrder: z.number().int().default(0),
});

export interface FinancialNote {
  id: string;
  orgId: string;
  noteNumber: string;
  title: string;
  content: string | null;
  autoGenerated: boolean;
  sourceReport: string | null;
  reportDate: Date | null;
  noteData: any;
  sortOrder: number;
}

export async function getNotes(orgId: string, sourceReport?: string): Promise<FinancialNote[]> {
  const conditions = [eq(financialNotes.orgId, orgId)];
  if (sourceReport) conditions.push(eq(financialNotes.sourceReport, sourceReport));

  const rows = await db
    .select()
    .from(financialNotes)
    .where(and(...conditions))
    .orderBy(financialNotes.sortOrder);

  return rows.map(r => ({
    id: r.id,
    orgId: r.orgId,
    noteNumber: r.noteNumber,
    title: r.title,
    content: r.content,
    autoGenerated: r.autoGenerated,
    sourceReport: r.sourceReport,
    reportDate: r.reportDate,
    noteData: r.noteData,
    sortOrder: r.sortOrder,
  }));
}

export async function saveNote(
  orgId: string,
  userId: string,
  data: z.infer<typeof noteSchema>,
  noteId?: string
): Promise<FinancialNote> {
  if (noteId) {
    const existing = await db
      .select()
      .from(financialNotes)
      .where(and(eq(financialNotes.id, noteId), eq(financialNotes.orgId, orgId)))
      .limit(1);

    if (existing.length === 0) throw new AppError('Note not found', 404);

    await db
      .update(financialNotes)
      .set({
        title: data.title,
        content: data.content,
        autoGenerated: data.autoGenerated,
        sourceReport: data.sourceReport,
        noteData: data.noteData,
        sortOrder: data.sortOrder,
        updatedBy: userId,
        updatedAt: new Date(),
      })
      .where(eq(financialNotes.id, noteId));

    const notes = await getNotes(orgId);
    return notes.find(n => n.id === noteId)!;
  }

  await db.insert(financialNotes).values({
    orgId,
    noteNumber: data.noteNumber,
    title: data.title,
    content: data.content || null,
    autoGenerated: data.autoGenerated,
    sourceReport: data.sourceReport || null,
    noteData: data.noteData || null,
    sortOrder: data.sortOrder,
    createdBy: userId,
    updatedBy: userId,
    reportDate: new Date(),
  });

  const notes = await getNotes(orgId);
  return notes.find(n => n.noteNumber === data.noteNumber && n.title === data.title)!;
}

export async function deleteNote(orgId: string, noteId: string): Promise<void> {
  const existing = await db
    .select()
    .from(financialNotes)
    .where(and(eq(financialNotes.id, noteId), eq(financialNotes.orgId, orgId)))
    .limit(1);

  if (existing.length === 0) throw new AppError('Note not found', 404);

  await db.delete(financialNotes).where(eq(financialNotes.id, noteId));
}

